//! NetBSD/luna88k (m88k) syscall number table.
//!
//! Numbers are authoritative from the guest's own
//! `/usr/include/sys/syscall.h` (`$NetBSD: syscall.h,v 1.156 2005/02/27$`,
//! generated from `syscalls.master,v 1.145`, `SYS_MAXSYSCALL = 375` — i.e. the
//! NetBSD 3.0.1 release on /mnt/netbsd). Cross-checked against the actual
//! `or r13,r0,<N>; tb0 0,r0,128` stubs in the static /bin utilities. See
//! docs/abi-netbsd.md.
//!
//! Convention (recovered): syscall number in r13, trap `tb0 0,r0,128`
//! (vector 128 = 0x80), args in r2..r12, return in r2 (r3 for the 2nd word of a
//! 64-bit return), carry-flag error signalling, skip-on-success PC.
//!
//! `syscall`(0) and `__syscall`(198) are the indirect forms: the real number
//! is the first argument (shift the argument window by one). NetBSD's libc
//! routes the 64-bit-offset calls (lseek/mmap/pread/pwrite/ftruncate/truncate)
//! through `__syscall`(198).
//!
//! Names follow the header's `SYS_` symbols, dropping the `compat_*`/`o*`
//! prefixes for the modern calls we actually service. Only the entries the
//! dispatcher switches on need to be named; unknown numbers fall through the
//! open-enum `_` arm to failFast.

